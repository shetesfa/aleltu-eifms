    $pdo = db();
    $dbName = DB_NAME;
    $filename = 'aleltu_eifms_backup_' . date('Y_m_d_His') . '.sql';

    // Increase execution time for large databases
    @set_time_limit(300);

    header('Content-Type: application/sql; charset=utf-8');
    header('Content-Disposition: attachment; filename="' . $filename . '"');
    header('Pragma: no-cache');
    header('Expires: 0');

    $out = fopen('php://output', 'w');

    fwrite($out, "-- ============================================================\n");
    fwrite($out, "-- Aleltu Farm EIFMS - Full Database Backup\n");
    fwrite($out, "-- Generated: " . date('Y-m-d H:i:s') . " (Ethiopian Date: " . eth_datetime(date('Y-m-d H:i:s')) . ")\n");
    fwrite($out, "-- Generated By: " . (current_user()['name'] ?? 'super_admin') . "\n");
    fwrite($out, "-- Database: {$dbName}\n");
    fwrite($out, "-- ============================================================\n\n");
    fwrite($out, "SET NAMES utf8mb4;\n");
    fwrite($out, "SET FOREIGN_KEY_CHECKS = 0;\n\n");

    $tables = $pdo->query("SHOW TABLES")->fetchAll(PDO::FETCH_COLUMN);

    foreach ($tables as $table) {
        fwrite($out, "-- ------------------------------------------------------------\n");
        fwrite($out, "-- Table structure for `{$table}`\n");
        fwrite($out, "-- ------------------------------------------------------------\n");
        fwrite($out, "DROP TABLE IF EXISTS `{$table}`;\n");

        $createStmt = $pdo->query("SHOW CREATE TABLE `{$table}`")->fetch(PDO::FETCH_ASSOC);
        $createSql = $createStmt['Create Table'] ?? '';
        fwrite($out, $createSql . ";\n\n");

        fwrite($out, "-- Data for `{$table}`\n");
        $rows = $pdo->query("SELECT * FROM `{$table}`");
        $rowCount = 0;

        while ($row = $rows->fetch(PDO::FETCH_ASSOC)) {
            $rowCount++;
            if ($rowCount % 500 === 1) {
                if ($rowCount > 1) {
                    fwrite($out, ";\n\n");
                }
                $cols = array_map(fn($c) => "`{$c}`", array_keys($row));
                fwrite($out, "INSERT INTO `{$table}` (" . implode(', ', $cols) . ") VALUES\n");
            } else {
                fwrite($out, ",\n");
            }

            $vals = array_map(function ($val) use ($pdo) {
                if ($val === null) return 'NULL';
                return $pdo->quote($val);
            }, array_values($row));

            fwrite($out, "(" . implode(', ', $vals) . ")");
        }

        if ($rowCount > 0) {
            fwrite($out, ";\n\n");
        } else {
            fwrite($out, "-- (No records)\n\n");
        }
    }

    fwrite($out, "SET FOREIGN_KEY_CHECKS = 1;\n");
    fwrite($out, "-- Backup completed successfully.\n");
    fclose($out);

    log_activity('admin', 'backup', 'database', 0, "Super admin downloaded full database backup ({$filename})");
    exit;
}

